#!/usr/bin/env python3
r"""Generate note/witness_table.tex from certificates/witness.json.

The coefficient table is machine-generated so that no digit of it is ever transcribed by
hand; verify_note_numbers.py regenerates it and fails if the committed file differs."""
import json
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def render():
    c = json.load(open(os.path.join(HERE, 'certificates', 'witness.json')))
    rows = []
    n = len(c['idx'])
    half = (n + 1) // 2
    for i in range(half):
        left = (i, c['idx'][i], c['coefficients'][i])
        if i + half < n:
            j = i + half
            right = (j, c['idx'][j], c['coefficients'][j])
            rows.append('$%d$ & $%d$ & $%s$ & $%d$ & $%d$ & $%s$ \\\\'
                        % (left[0], left[1], left[2], right[0], right[1], right[2]))
        else:
            rows.append('$%d$ & $%d$ & $%s$ & & & \\\\' % left)
    body = '\n'.join(rows)
    return ('%% generated by note/make_witness_table.py from certificates/witness.json\n'
            '%% DO NOT EDIT BY HAND\n'
            '\\begin{center}\\footnotesize\n'
            '\\begin{tabular}{@{}rrlrrl@{}}\n\\toprule\n'
            '$m$ & $k_m$ & $c_m$ & $m$ & $k_m$ & $c_m$ \\\\\n\\midrule\n'
            + body + '\n\\bottomrule\n\\end{tabular}\n\\end{center}\n')


if __name__ == '__main__':
    out = os.path.join(HERE, 'note', 'witness_table.tex')
    txt = render()
    if len(sys.argv) > 1 and sys.argv[1] == '--check':
        cur = open(out).read() if os.path.exists(out) else ''
        print('witness_table.tex MATCHES generator' if cur == txt
              else 'witness_table.tex DIFFERS from generator')
        sys.exit(0 if cur == txt else 1)
    with open(out, 'w') as fh:
        fh.write(txt)
    print('wrote %s' % out)
