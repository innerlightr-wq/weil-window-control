#!/usr/bin/env python3
r"""Generate the Siegel note's numeric tables from the data, correctly ROUNDED.

Typing a high-precision value into LaTeX by hand truncates it, and the verifier treats a
truncation as a disagreement -- which is how the companion DH note's first-draft tables
were caught.  These tables are machine-generated; the verifier regenerates and compares
them."""
import csv
import json
import os
import sys
from decimal import Decimal, ROUND_HALF_UP
from fractions import Fraction

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import registry as reg                                                   # noqa: E402

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NOTE = os.path.join(HERE, 'note')
DATA = os.path.join(HERE, 'data')
RES = os.path.join(HERE, 'results')
HDR = ('%% generated by note/make_tables.py from the data files\n'
       '%% DO NOT EDIT BY HAND\n')


def rs(x, n):
    x = Decimal(str(x))
    if x == 0:
        return Decimal(0)
    return x.quantize(Decimal(1).scaleb(x.adjusted() - n + 1), rounding=ROUND_HALF_UP)


def tex(x, n):
    v = rs(x, n)
    if v == 0:
        return '$0$'
    e = v.adjusted()
    if -4 < e < 6:
        return '$%s$' % format(v, 'f').rstrip('0').rstrip('.')
    return '$%s\\times10^{%d}$' % (format(v.scaleb(-e), 'f').rstrip('0').rstrip('.'), e)


CH = {'zeta': r'$\zeta$', 'chi_-3': r'$\chi_{-3}$', 'chi_-4': r'$\chi_{-4}$',
      'chi_5': r'$\chi_{5}$', 'chi_-7': r'$\chi_{-7}$', 'chi_8': r'$\chi_{8}$'}


def read_csv(p):
    with open(p) as fh:
        return list(csv.DictReader(l for l in fh if not l.startswith('#')))


def eig_table():
    """Check (b): the perturbation eigenvalue is chi-independent, so one row per
    (L, delta) with the even and odd values."""
    vs = read_csv(os.path.join(DATA, 'verify_siegel_parity.csv'))
    # only the extreme delta are printed; the full 150 cells are in the CSV
    KEEP = ('0.1', '0.49')
    seen, rows = set(), []
    for r in vs:
        key = (r['L'], r['delta'])
        if key in seen or r['delta'] not in KEEP:
            continue
        seen.add(key)
        ev = [x for x in vs if x['L'] == r['L'] and x['delta'] == r['delta']
              and x['sector'] != 'odd'][0]
        od = [x for x in vs if x['L'] == r['L'] and x['delta'] == r['delta']
              and x['sector'] == 'odd'][0]
        rows.append('$%s$ & $%s$ & %s & %s & %s & %s \\\\'
                    % (r['L'], r['delta'], tex(ev['eigenvalue'], 12),
                       tex(od['eigenvalue'], 12),
                       tex(max(float(ev['rank1_residual']),
                               float(od['rank1_residual'])), 3),
                       tex(max(float(ev['rel_err']), float(od['rel_err'])), 3)))
    rows.sort(key=lambda t: (float(t.split('$')[1]), float(t.split('$')[3])))
    return (HDR + '\\begin{center}\\small\n\\begin{tabular}{@{}llllll@{}}\n\\toprule\n'
            '$L$ & $\\delta$ & $+2A_\\delta^2$ (even) & $-2S_\\delta^2$ (odd)'
            ' & rank-one resid. & rel.\\ err. \\\\\n\\midrule\n'
            + '\n'.join(rows) + '\n\\bottomrule\n\\end{tabular}\n\\end{center}\n')


def pole_table():
    j = json.load(open(os.path.join(RES, 'verify_siegel_parity.json')))['results']['c']
    name = {'even_d': '\\textsc{even\\_d}', 'even': '\\textsc{even}', 'odd': '\\textsc{odd}'}
    rows = []
    for key in sorted(j, key=lambda k: (k.split('|')[0], float(k.split('|')[1]))):
        sec, L = key.split('|')
        v = j[key]
        rows.append('%s & $%s$ & $%+d$ & %s & %s & %s \\\\'
                    % (name[sec], L, v['pole_sign'],
                       tex(float(v['max_abs_B_minus_Pole']), 3),
                       tex(float(v['max_abs_B_plus_Pole']), 4),
                       v['vanishes'].replace('-', '$-$')))
    return (HDR + '\\begin{center}\\small\n\\begin{tabular}{@{}llllll@{}}\n\\toprule\n'
            'sector & $L$ & pole sign & $\\max|B-\\mathrm{Pole}|$'
            ' & $\\max|B+\\mathrm{Pole}|$ & vanishes \\\\\n\\midrule\n'
            + '\n'.join(rows) + '\n\\bottomrule\n\\end{tabular}\n\\end{center}\n')


def onset_table():
    on = read_csv(os.path.join(DATA, 'phase5_onset_odd.csv'))
    labs, dels = [], []
    for r in on:
        if r['label'] not in labs:
            labs.append(r['label'])
        if r['delta'] not in dels:
            dels.append(r['delta'])
    dels.sort(key=float)
    rows = []
    for lab in labs:
        cells = []
        for d in dels:
            hits = [float(r['L']) for r in on if r['label'] == lab
                    and r['delta'] == d and r['detected'] == 'yes']
            cells.append('$%g$' % min(hits) if hits else '---')
        rows.append('%s & %s \\\\' % (CH[lab], ' & '.join(cells)))
    return (HDR + '\\begin{center}\\small\n\\begin{tabular}{@{}l%s@{}}\n\\toprule\n'
            % ('l' * len(dels))
            + ' & ' + ' & '.join('$\\delta=%s$' % d for d in dels)
            + ' \\\\\n\\midrule\n' + '\n'.join(rows)
            + '\n\\bottomrule\n\\end{tabular}\n\\end{center}\n')


def ff_table():
    rows = json.load(open(os.path.join(RES, 'ff_parity_split.json')))['rows']
    rhos, Rs = [], []
    for r in rows:
        if r['rho'] not in rhos:
            rhos.append(r['rho'])
        if r['R'] not in Rs:
            Rs.append(r['R'])
    Rs.sort()
    Rs = [R for R in Rs if R <= 4]      # R = 8, 16 are verified but their exact
    out = []                            # rationals run to 22 digits and are not printed
    for rho in rhos:
        cells = []
        for R in Rs:
            m = [r for r in rows if r['rho'] == rho and r['R'] == R]
            cells.append('$%s$' % str(Fraction(m[0]['lam_minus'])).replace(
                '/', '/') if m else '---')
        out.append('$%s$ & %s \\\\' % (rho, ' & '.join(cells)))
    return (HDR + '\\begin{center}\\small\n\\begin{tabular}{@{}l%s@{}}\n\\toprule\n'
            % ('l' * len(Rs))
            + '$\\rho$ & ' + ' & '.join('$R=%d$' % R for R in Rs)
            + ' \\\\\n\\midrule\n' + '\n'.join(out)
            + '\n\\bottomrule\n\\end{tabular}\n\\end{center}\n')


def K_table():
    k4 = read_csv(os.path.join(DATA, 'phase4b_sector_extremal.csv'))
    rows = []
    for r in k4:
        if r['gamma'] != '0':
            continue
        rows.append('$%s$ & %s & %s & %s & %s \\\\'
                    % (r['L'], tex(r['K_even'], 1), tex(r['K_odd'], 12),
                       tex(r['two_L3_3'], 12), tex(float(r['abs_err']), 3)))
    return (HDR + '\\begin{center}\\small\n\\begin{tabular}{@{}lllll@{}}\n\\toprule\n'
            '$L$ & $K_{\\mathrm{even}}(L,0)$ & $K_{\\mathrm{odd}}(L,0)$'
            ' & $2L^3/3$ & $|{\\rm err}|$ \\\\\n\\midrule\n'
            + '\n'.join(rows) + '\n\\bottomrule\n\\end{tabular}\n\\end{center}\n')


TABLES = dict(eig_table=eig_table, pole_table=pole_table, onset_table=onset_table,
              ff_table=ff_table, K_table=K_table)


def main():
    bad = 0
    for name, fn in TABLES.items():
        txt = fn()
        path = os.path.join(NOTE, name + '.tex')
        if len(sys.argv) > 1 and sys.argv[1] == '--check':
            cur = open(path).read() if os.path.exists(path) else ''
            ok = cur == txt
            print('  %-14s %s' % (name, 'MATCHES generator' if ok else 'DIFFERS'))
            bad += 0 if ok else 1
        else:
            with open(path, 'w') as fh:
                fh.write(txt)
            print('wrote %s' % os.path.relpath(path, HERE))
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
