#!/usr/bin/env python3
r"""Generate the note's numeric tables from the registry, correctly ROUNDED.

Typing a high-precision value into LaTeX by hand truncates it; the verifier treats a
truncation as a disagreement, which is how the first draft's tables were caught.  These
tables are therefore machine-generated and the verifier regenerates and compares them."""
import os
import sys
from decimal import Decimal, ROUND_HALF_UP

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import registry as reg                                                   # noqa: E402

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NOTE = os.path.join(HERE, 'note')
HDR = ('%% generated by note/make_tables.py from the data files\n'
       '%% DO NOT EDIT BY HAND\n')


def rs(x, n):
    if x == 0:
        return Decimal(0)
    return x.quantize(Decimal(1).scaleb(x.adjusted() - n + 1), rounding=ROUND_HALF_UP)


def tex(x, n):
    """LaTeX for a value rounded to n significant digits."""
    v = rs(Decimal(x), n)
    s = format(v, 'f')
    if 'E' in s or 'e' in s:
        s = format(v, 'f')
    exp = v.adjusted()
    if -4 < exp < 6:
        return '$%s$' % s.rstrip('.') if '.' in s else '$%s$' % s
    mant = v.scaleb(-exp)
    return '$%s\\times10^{%d}$' % (format(mant, 'f'), exp)


def census_table(R):
    rows = []
    for i in (1, 2, 3, 4):
        rows.append('$O_%d$ & %s & %s & %s & %s & $1$ \\\\' % (
            i, tex(R['O%d_beta' % i]['value'], 18),
            tex(R['O%d_gamma' % i]['value'], 18),
            tex(R['O%d_delta' % i]['value'], 18),
            tex(R['O%d_absF' % i]['value'], 3)))
    return (HDR + '\\begin{center}\\small\n\\begin{tabular}{@{}llllll@{}}\n\\toprule\n'
            ' & $\\beta$ & $\\gamma$ & $\\delta=\\beta-\\tfrac12$ & $|f(\\rho)|$ &'
            ' winding \\\\\n\\midrule\n' + '\n'.join(rows)
            + '\n\\bottomrule\n\\end{tabular}\n\\end{center}\n')


WINDOWS = ['1.0', '1.2', '1.4', '1.6', '1.8', '2.0', '2.2', '2.4', '2.6']


def remaining_table(R):
    rows = []
    for L in WINDOWS:
        k = L.replace('.', '')
        rows.append('$%s$ & %s & %s & %s & %s \\\\' % (
            L,
            tex(R['scan_%s_even_d_2' % k]['value'], 13),
            tex(R['rest_%s_even_d' % k]['value'], 12),
            tex(R['scan_%s_odd_2' % k]['value'], 13),
            tex(R['rest_%s_odd' % k]['value'], 12)))
    return (HDR + '\\begin{center}\\small\n\\begin{tabular}{@{}lllll@{}}\n\\toprule\n'
            '$L$ & $\\lmin(Q_f)$, even & $\\lmin(\\Qrest)$, even'
            ' & $\\lmin(Q_f)$, odd & $\\lmin(\\Qrest)$, odd \\\\\n\\midrule\n'
            + '\n'.join(rows) + '\n\\bottomrule\n\\end{tabular}\n\\end{center}\n')


def onset_table(R):
    rows = []
    for L in ('1.6', '1.8', '2.0'):
        k = L.replace('.', '')
        cells = [tex(R['scan_%s_%s_%s' % (k, sec, lev)]['value'], 12)
                 for sec in ('even_d', 'odd') for lev in ('1', '2', '3')]
        rows.append('$%s$ & %s \\\\' % (L, ' & '.join(cells)))
    return (HDR + '\\begin{center}\\footnotesize\n'
            '\\begin{tabular}{@{}lllllll@{}}\n\\toprule\n'
            '$L$ & even, lvl 1 & even, lvl 2 & even, lvl 3'
            ' & odd, lvl 1 & odd, lvl 2 & odd, lvl 3 \\\\\n\\midrule\n'
            + '\n'.join(rows) + '\n\\bottomrule\n\\end{tabular}\n\\end{center}\n')


TABLES = dict(census_table=census_table, remaining_table=remaining_table,
              onset_table=onset_table)


def main():
    R = reg.build()
    bad = 0
    for name, fn in TABLES.items():
        txt = fn(R)
        path = os.path.join(NOTE, name + '.tex')
        if len(sys.argv) > 1 and sys.argv[1] == '--check':
            cur = open(path).read() if os.path.exists(path) else ''
            ok = cur == txt
            print('  %-18s %s' % (name, 'MATCHES generator' if ok else 'DIFFERS'))
            bad += 0 if ok else 1
        else:
            with open(path, 'w') as fh:
                fh.write(txt)
            print('wrote %s' % path)
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
